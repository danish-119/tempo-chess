export const OPENING_GROUPS = [...new Set(OPENINGS.map((o) => o.group))];

export function openingById(id: string | null | undefined): OpeningLesson | null {
  return OPENINGS.find((o) => o.id === id) ?? null;
}

/** What the coach says, and the page shows, when move number `ply` (1-based) is played. */
export function moveNarration(opening: OpeningLesson, ply: number, san: string): string {
  const side = ply % 2 === 1 ? "White" : "Black";
  return [`${side} plays ${san}.`, opening.notes[ply]].filter(Boolean).join(" ");
}
