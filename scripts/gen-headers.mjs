// Generates vercel.json and public/_headers from scripts/headers.mjs.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { ENGINE_CACHE, SECURITY_HEADERS } from "./headers.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const entries = Object.entries(SECURITY_HEADERS);

const vercel = {
  $schema: "https://openapi.vercel.sh/vercel.json",
  // Static export: deploy out/ as plain files. The Next.js preset would expect a
  // server build (.next / routes-manifest.json) and fail with NEXT_NO_ROUTES_MANIFEST.
  framework: null,
  buildCommand: "npm run build",
  outputDirectory: "out",
  cleanUrls: true,
  headers: [
    { source: "/(.*)", headers: entries.map(([key, value]) => ({ key, value })) },
    {
      source: "/engine/(.*)\\.wasm",
      headers: [
        { key: "Content-Type", value: "application/wasm" },
        { key: "Cache-Control", value: ENGINE_CACHE },
      ],
    },
    { source: "/engine/(.*)\\.js", headers: [{ key: "Cache-Control", value: ENGINE_CACHE }] },
  ],
};
writeFileSync(join(root, "vercel.json"), `${JSON.stringify(vercel, null, 2)}\n`);

const netlify = [
  "# Generated by scripts/gen-headers.mjs — do not edit by hand.",
  "/*",
  ...entries.map(([k, v]) => `  ${k}: ${v}`),
  "",
  "/engine/*",
  `  Cache-Control: ${ENGINE_CACHE}`,
  "",
].join("\n");
writeFileSync(join(root, "public", "_headers"), netlify);
console.log("Wrote vercel.json and public/_headers");
